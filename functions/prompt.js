export function generatePrompt({
  userName,
  userQuestion,
  topic,
  situation,
  notes,
  fortunesSummary,
}) {
  return `以下の素材をもとに相談者「${userName}」に向けて日本語の約5000字の助言文（エッセイ形式）を生成してください。。
- 日本語で書いてください。
- 章構成は以下の流れに沿ってください。ただし、小見出し（タイトル）や番号は入れないでください。文章はひと続きの語り口で展開してください。

  1. 心情の受容と共感（冒頭）
  2. 状況の整理と現在の意味づけ
  3. 変化に向けた準備と問い直しの重要性
  4. 社会的文脈と複数の選択肢の提示
  5. 方向の明確化と実践的な気づきの提案
  6. 最後に背中をそっと押す、温かい励ましの結び

- 抽象的な表現（「焦らずに」「風のように」「可能性が広がる」など）に終始せず、現実にあり得る行動、態度、考え方の提案を必ず含めてください。
- 易卦の名称をいちいち繰り返さず、象徴としての意味をやわらかく文章に溶け込ませてください。
- 読み手が「わたしのことを見てくれている」と感じられるよう、状況と感情にしっかりと寄り添ってください。
※文字数は日本語で約5000字を目安にしてください。短く要約したり、語りを打ち切らず、 相談者が1つの手紙を受け取ったように感じられる長さで丁寧に書いてください。

---
【相談者名】
${userName}
【質問】
${userQuestion}
【背景】
${topic}
【状況】
${situation}
【補足メモ】
${notes}
【総合的な易断（卦のまとめ）】
${fortunesSummary}
`;
}
